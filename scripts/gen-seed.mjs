// Generates supabase/migrations/0002_seed_strategies.sql from data/records.json.
// Usage: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const STRATEGIES = [
  ["kitchen", "Kitchen Money AI", "All in one", 1],
  ["gold", "Gold AI", "Gold", 2],
  ["crypto", "Crypto AI", "Crypto", 3],
  ["ecom", "Ecom AI", "E-commerce", 4],
  ["sat", "Satellite AI", "Satellite", 5],
  ["prompt", "Prompts AI", "AI prompts", 6],
];
const NOTE = "Published monthly record, imported from the approved handoff (records.json)";
const MTD_NOTE = "Month-to-date figure, imported from the approved handoff (records.json)";

const { records, mtd } = JSON.parse(readFileSync("data/records.json", "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const rows = [];
for (const [slug] of STRATEGIES) {
  for (const { ym, r } of records[slug]) rows.push([slug, ym, r, "published", NOTE]);
  if (mtd && mtd[slug] != null) rows.push([slug, mtd.ym, mtd[slug], "mtd", MTD_NOTE]);
}

const sql = `-- Generated by scripts/gen-seed.mjs from data/records.json. Do not edit by hand.
-- Existing rows are left alone, so re-running never overwrites a figure the owner has published.

insert into public.strategies (slug, name, kind, sort_order) values
${STRATEGIES.map(([s, n, k, o]) => `  (${q(s)}, ${q(n)}, ${q(k)}, ${o})`).join(",\n")}
on conflict (slug) do nothing;

insert into public.strategy_returns (strategy_id, ym, return_pct, status, source_note, published_at)
select s.id, v.ym::date, v.r, v.status::public.return_status, v.note,
       case when v.status = 'published' then now() end
from (values
${rows.map(([s, ym, r, st, n]) => `  (${q(s)}, ${q(ym + "-01")}, ${r}, ${q(st)}, ${q(n)})`).join(",\n")}
) as v(slug, ym, r, status, note)
join public.strategies s on s.slug = v.slug
on conflict (strategy_id, ym) do nothing;
`;
writeFileSync("supabase/migrations/0002_seed_strategies.sql", sql);
console.log(`wrote ${rows.length} return rows for ${STRATEGIES.length} strategies`);
